import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const REF = process.env.LUCIDE_REF || 'main';
const OUT = path.resolve('src/generated/lucide-icon-meta.js');

async function fetchJson(url) {
  const res = await fetch(url, {
    headers: {
      Accept: 'application/json',
      'User-Agent': 'yanta-icon-index-builder',
    },
  });

  if (!res.ok) {
    throw new Error(`Fetch failed ${res.status}: ${url}`);
  }

  return res.json();
}

async function main() {
  console.log(`[lucide-index] Fetching Lucide tree ref=${REF}`);

  const tree = await fetchJson(
    `https://api.github.com/repos/lucide-icons/lucide/git/trees/${encodeURIComponent(REF)}?recursive=1`
  );

  const jsonPaths = (tree.tree || [])
    .map((x) => x.path)
    .filter((p) => /^icons\/[^/]+\.json$/.test(p))
    .sort();

  console.log(`[lucide-index] Found ${jsonPaths.length} metadata files`);

  const items = [];

  // simple concurrency limit
  const queue = [...jsonPaths];
  const workers = Array.from({ length: 16 }, async () => {
    while (queue.length) {
      const p = queue.shift();
      const name = p.split('/').pop().replace(/\.json$/, '');

      const rawUrl =
        `https://raw.githubusercontent.com/lucide-icons/lucide/${encodeURIComponent(REF)}/${p}`;

      try {
        const meta = await fetchJson(rawUrl);

        const aliases = [];
        const deprecatedAliases = [];

        for (const a of meta.aliases || []) {
          if (!a?.name) continue;

          if (a.deprecated) deprecatedAliases.push(a.name);
          else aliases.push(a.name);
        }

        items.push({
          n: name,
          t: Array.isArray(meta.tags) ? meta.tags : [],
          c: Array.isArray(meta.categories) ? meta.categories : [],
          a: aliases,
          da: deprecatedAliases,
          d: meta.deprecated === true,
        });
      } catch (err) {
        console.warn(`[lucide-index] Skipped ${p}: ${err.message}`);
      }
    }
  });

  await Promise.all(workers);

  items.sort((a, b) => a.n.localeCompare(b.n));

  const code = `// Auto-generated by scripts/build-lucide-icon-index.mjs
// Lucide ref: ${REF}
// Do not edit manually.

export const LUCIDE_ICON_META = ${JSON.stringify(items)};
`;

  await mkdir(path.dirname(OUT), { recursive: true });
  await writeFile(OUT, code);

  console.log(`[lucide-index] Wrote ${items.length} icons to ${OUT}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});