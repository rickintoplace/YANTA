import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
// Wir importieren die bereits existierenden Metadaten direkt aus dem Paket
import { tags } from 'lucide/metadata.js'; 

const OUT = path.resolve('src/generated/lucide-icon-meta.js');

async function main() {
  console.log(`[lucide-index] Processing local Lucide metadata...`);

  // Transformiert die Daten in dein gewünschtes Format
  const items = Object.entries(tags).map(([name, meta]) => {
    const aliases = [];
    const deprecatedAliases = [];

    for (const a of meta.aliases || []) {
      if (!a?.name) continue;
      if (a.deprecated) deprecatedAliases.push(a.name);
      else aliases.push(a.name);
    }

    return {
      n: name,
      t: Array.isArray(meta.tags) ? meta.tags : [],
      c: Array.isArray(meta.categories) ? meta.categories : [],
      a: aliases,
      da: deprecatedAliases,
      d: meta.deprecated === true,
    };
  });

  items.sort((a, b) => a.n.localeCompare(b.n));

  const code = `// Auto-generated by scripts/build-lucide-icon-index.mjs
// Generated from local lucide package
// Do not edit manually.

export const LUCIDE_ICON_META = ${JSON.stringify(items, null, 2)};
`;

  await mkdir(path.dirname(OUT), { recursive: true });
  await writeFile(OUT, code);

  console.log(`[lucide-index] Wrote ${items.length} icons to ${OUT}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});