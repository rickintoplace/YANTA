#!/usr/bin/env node
// ============================================================
// Generates src/icons/lucide-subset.js: the Lucide icons whose names
// appear as string literals anywhere in src/ or index.html.
//
// The full set (~2,000 icons) is ~430 KB of the boot bundle; the app
// names a few hundred. Everything else — icons users picked for their
// notes, names built at runtime — comes from the full set, which
// core.js loads lazily and then patches into placeholders.
//
// Runs before dev and build. Over-matching is fine (a word that happens
// to be an icon name costs a few hundred bytes); missing is fine too
// (the icon renders once the full set arrives).
// ============================================================

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { icons } from 'lucide';

const root = fileURLToPath(new URL('..', import.meta.url));
const out = join(root, 'src/icons/lucide-subset.js');

const kebab = (key) => key
  .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
  .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
  .replace(/([a-z])([0-9])/g, '$1-$2')
  .toLowerCase();

// Lucide keys like "Grid2x2" kebab differently depending on the rule
// used, so accept both spellings.
const byName = new Map();
for (const key of Object.keys(icons)) {
  byName.set(kebab(key), key);
  byName.set(key.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').toLowerCase(), key);
}

function* files(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* files(path);
    else if (/\.(js|mjs|html)$/.test(name) && path !== out) yield path;
  }
}

const used = new Set();
const LITERAL = /(['"`])([a-z][a-z0-9-]{0,40})\1/g;

for (const path of [...files(join(root, 'src')), join(root, 'index.html')]) {
  for (const [, , name] of readFileSync(path, 'utf8').matchAll(LITERAL)) {
    const key = byName.get(name);
    if (key) used.add(key);
  }
}

// The fallback icon must always be there.
for (const name of ['square', 'box']) used.add(byName.get(name));

const keys = [...used].filter(Boolean).sort();

writeFileSync(out, [
  '// Generated by scripts/gen-lucide-subset.mjs — do not edit.',
  `// ${keys.length} of ${Object.keys(icons).length} Lucide icons, the ones named in ${relative(root, join(root, 'src'))}/.`,
  'export const LUCIDE_SUBSET = {',
  ...keys.map((key) => `  ${key}: ${JSON.stringify(icons[key])},`),
  '};',
  '',
].join('\n'));

console.log(`lucide subset: ${keys.length} of ${Object.keys(icons).length} icons → ${relative(root, out)}`);
