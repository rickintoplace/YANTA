function eventId(event) {
  return event?.getId?.() || event?.event?.event_id || '';
}

function eventTs(event) {
  return Number(event?.getTs?.() || event?.event?.origin_server_ts || 0);
}

function sameDay(a, b) {
  const da = new Date(a);
  const db = new Date(b);

  return da.toDateString() === db.toDateString();
}

function dayLabel(ts) {
  const d = new Date(ts || Date.now());
  const today = new Date();

  const yesterday = new Date();
  yesterday.setDate(today.getDate() - 1);

  if (sameDay(d, today)) return 'Today';
  if (sameDay(d, yesterday)) return 'Yesterday';

  return d.toLocaleDateString([], {
    weekday: 'short',
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });
}

function timeLabel(ts) {
  try {
    return new Date(ts || Date.now()).toLocaleTimeString([], {
      hour: '2-digit',
      minute: '2-digit',
    });
  } catch {
    return '';
  }
}

function senderName(room, userId) {
  const member = room?.getMember?.(userId);

  return (
    member?.name ||
    member?.rawDisplayName ||
    member?.displayName ||
    userId ||
    'Unknown'
  );
}

function clearContent(event) {
  return (
    event?.getClearContent?.() ||
    event?.getContent?.() ||
    event?.event?.content ||
    {}
  );
}

function replacementEvent(event) {
  try {
    return event.replacingEvent?.() || event.getAssociatedReplacement?.() || null;
  } catch {
    return null;
  }
}

function effectiveContent(event) {
  const replacement = replacementEvent(event);

  if (replacement) {
    const content = clearContent(replacement);

    if (content?.['m.new_content']) {
      return {
        content: content['m.new_content'],
        edited: true,
      };
    }
  }

  const content = clearContent(event);

  return {
    content,
    edited: false,
  };
}

function isEditEvent(event) {
  const content = clearContent(event);
  const relates = content?.['m.relates_to'] || {};

  return relates.rel_type === 'm.replace';
}

/*
  isRedacted() darf nur die REDIGIERTE Original-Nachricht erkennen.
  Das m.room.redaction-Event selbst ist das neueste Timeline-Event und
  wurde bisher als "Message deleted" ganz unten gerendert.
*/
function isRedacted(event) {
  return (
    event?.isRedacted?.() === true ||
    !!event?.event?.unsigned?.redacted_because
  );
}

function isMessageLike(event) {
  const type = event?.getType?.();
  return type === 'm.room.message' || type === 'm.sticker';
}

function linkifyEscapedText(text) {
  const escaped = escapeHtml(String(text || ''));

  return escaped.replace(
    /\b((?:https?:\/\/|mailto:)[^\s<]+)/gi,
    (full) => {
      const href = full.replace(/[),.;!?]+$/, '');
      const tail = full.slice(href.length);

      return `<a href="${href}" target="_blank" rel="noopener noreferrer">${href}</a>${tail}`;
    }
  ).replace(/\n/g, '<br>');
}

function sanitizeFormattedBody(html) {
  /*
    Why:
    Matrix federation means formatted_body can be supplied by any remote
    homeserver/client. Rendering arbitrary HTML would create XSS risk.
    We keep a tiny allowlist and normalize links after sanitizing.
  */
  const safe = DOMPurify.sanitize(String(html || ''), {
    ALLOWED_TAGS: SAFE_FORMATTED_BODY_TAGS,
    ALLOWED_ATTR: SAFE_FORMATTED_BODY_ATTRS,
    ALLOW_DATA_ATTR: false,
  });

  const tmp = document.createElement('div');
  tmp.innerHTML = safe;

  for (const a of tmp.querySelectorAll('a[href]')) {
    const href = a.getAttribute('href') || '';

    if (!/^(https?:|mailto:)/i.test(href)) {
      a.removeAttribute('href');
      continue;
    }

    a.target = '_blank';
    a.rel = 'noopener noreferrer';
  }

  return tmp.innerHTML;
}

function mediaLabel(msgtype) {
  if (msgtype === 'm.image') return 'Photo';
  if (msgtype === 'm.video') return 'Video';
  if (msgtype === 'm.audio') return 'Audio';
  if (msgtype === 'm.file') return 'File';
  return 'Attachment';
}

function bodyPreviewFromContent(content = {}) {
  const msgtype = content.msgtype || '';

  if (msgtype && msgtype !== 'm.text' && msgtype !== 'm.notice' && msgtype !== 'm.emote') {
    return mediaLabel(msgtype);
  }

  return String(content.body || '').trim();
}

/**
 * Create a short preview for room lists and replies.
 */
export function messagePreview(event) {
  if (!event) return '';

  if (isRedacted(event)) return 'Message deleted';

  const {
    content,
    edited,
  } = effectiveContent(event);

  const aiGenerated = contentIsYantaAiGenerated(content, {
    allowFooterFallback: true,
  });
  const cleanContent = displayContent(content);
  const preview = bodyPreviewFromContent(cleanContent);

  const suffixes = [];

  if (aiGenerated && preview) suffixes.push('AI');
  if (edited && preview) suffixes.push('edited');

  return suffixes.length
    ? `${preview} · ${suffixes.join(' · ')}`
    : preview;
}

function renderTextContent(content = {}) {
  const node = el('div', {
    class: 'yanta-chat-message-text',
  });

  const formatted =
    content.format === 'org.matrix.custom.html'
      ? String(content.formatted_body || '')
      : '';

  const cleanFormatted = formatted.trim();

  node.innerHTML = cleanFormatted
    ? sanitizeFormattedBody(cleanFormatted)
    : linkifyEscapedText(content.body || '');

  return node;
}

function renderMessageBody(client, content = {}, context = {}) {
  const msgtype = content.msgtype || 'm.text';

  if (
    msgtype === 'm.image' ||
    msgtype === 'm.video' ||
    msgtype === 'm.audio' ||
    msgtype === 'm.file'
  ) {
    return renderChatMediaContent(client, content, context);
  }

  return renderTextContent(content);
}

function readByOther(room, event, ownUserId) {
  try {
    /*
      Important:
      Matrix attaches a read receipt only to the LAST event a user read.
      Older messages carry no receipt themselves but are implicitly read.
      getUsersReadUpTo()/getReceiptsForEvent() only return exact matches on
      this event — with them, only the newest own message ever shows "read".
      room.hasUserReadEvent() respects the receipt ordering.
    */
    const id = eventId(event);

    if (id && typeof room?.hasUserReadEvent === 'function') {
      const members = room.getJoinedMembers?.() || [];

      return members.some((member) =>
        member?.userId &&
        member.userId !== ownUserId &&
        room.hasUserReadEvent(member.userId, id)
      );
    }

    // Fallback for SDK builds without hasUserReadEvent: exact receipts only.
    const users = room.getUsersReadUpTo?.(event) || [];

    return users.some((userId) => userId && userId !== ownUserId);
  } catch {
    return false;
  }
}

function statusIcon(client, room, event) {
  const ownUserId = client?.getUserId?.() || '';
  const sender = event?.getSender?.() || event?.sender?.userId || '';

  if (!ownUserId || sender !== ownUserId) return null;

  const status = String(event.status || '');

  const wrap = el('span', {
    class: 'yanta-chat-status',
    title: 'Message status',
  });

  if (status && status !== 'sent') {
    wrap.classList.add('is-sending');
    wrap.innerHTML = lucide('circle-dashed', 12);
    wrap.title = 'Sending';
    return wrap;
  }

  if (readByOther(room, event, ownUserId)) {
    wrap.classList.add('is-read');
    wrap.innerHTML = lucide('check-check', 12);
    wrap.title = 'Read';
    return wrap;
  }

  /*
    Matrix does not expose Signal-style "delivered to device" receipts by
    default. This is server-accepted/sent state.
  */
  wrap.classList.add('is-sent');
  wrap.innerHTML = lucide('check', 12);
  wrap.title = 'Sent';
  return wrap;
}
function replyPreviewNode(event, eventMap, room) {
  const content = clearContent(event);
  const replyId = content?.['m.relates_to']?.['m.in_reply_to']?.event_id;

  if (!replyId) return null;

  const replied = eventMap.get(replyId);
  const sender = replied?.getSender?.() || '';
  const preview = replied
    ? messagePreview(replied)
    : 'Original message';

  const node = el('div', {
    class: 'yanta-chat-reply-preview',
  });

  node.innerHTML = `
    <strong>${escapeHtml(senderName(room, sender))}</strong>
    <span>${escapeHtml(preview || 'Message')}</span>
  `;

  return node;
}

function renderSingleMessage(event, {
  client,
  room,
  grouped,
  eventMap,
} = {}) {
  if (!isMessageLike(event)) return null;
  if (isEditEvent(event)) return null;

  const ownUserId = client?.getUserId?.() || '';
  const sender = event.getSender?.() || '';
  const outgoing = sender === ownUserId;

  const row = el('div', {
    class: `yanta-chat-event ${outgoing ? 'own' : 'other'} ${grouped ? 'grouped' : ''}`,
    dataset: {
      eventId: eventId(event),
    },
  });

  const bubble = el('div', {
    class: 'yanta-chat-bubble',
  });

  if (!grouped && !outgoing) {
    bubble.append(el('div', {
      class: 'yanta-chat-sender',
    }, senderName(room, sender)));
  }

  if (isRedacted(event)) {
    bubble.append(el('div', {
      class: 'yanta-chat-redacted',
    }, 'Message deleted'));
  } else {
    const reply = replyPreviewNode(event, eventMap, room);

    if (reply) {
      bubble.append(reply);
    }

    const {
      content,
      edited,
    } = effectiveContent(event);

    const aiGenerated = contentIsYantaAiGenerated(content, {
      allowFooterFallback: outgoing,
    });
    const cleanContent = displayContent(content);

    if (aiGenerated) {
      bubble.classList.add('is-ai-generated');
      bubble.append(renderYantaAiBanner());
    }

    bubble.append(renderMessageBody(client, cleanContent, {
      roomId: room?.roomId || '',
      eventId: eventId(event),
    }));

    if (edited) {
      bubble.append(el('span', {
        class: 'yanta-chat-edited',
      }, 'edited'));
    }
  }

  const meta = el('div', {
    class: 'yanta-chat-meta',
  });

  meta.append(el('span', {}, timeLabel(eventTs(event))));

  const status = statusIcon(client, room, event);

  if (status) {
    meta.append(status);
  }

  bubble.append(meta);
  row.append(bubble);

  return row;
}

function isRenderableStateEvent(event) {
  const type = event?.getType?.() || event?.event?.type || '';

  return (
    type === 'm.room.member' ||
    type === 'm.room.name' ||
    type === 'm.room.avatar' ||
    type === 'm.room.topic'
  );
}

function stateEventText(event, room) {
  const type = event?.getType?.() || event?.event?.type || '';
  const sender = event?.getSender?.() || event?.event?.sender || '';
  const content = event?.getContent?.() || event?.event?.content || {};
  const prev = event?.event?.unsigned?.prev_content || {};

  if (type === 'm.room.name') {
    const next = String(content.name || '').trim();
    const before = String(prev.name || '').trim();

    if (next && before && next !== before) {
      return `${senderName(room, sender)} changed the chat name to “${next}”.`;
    }

    if (next) return `${senderName(room, sender)} named the chat “${next}”.`;
  }

  if (type === 'm.room.topic') {
    const next = String(content.topic || '').trim();
    if (next) return `${senderName(room, sender)} changed the topic.`;
  }

  if (type === 'm.room.avatar') {
    return `${senderName(room, sender)} changed the chat picture.`;
  }

  if (type === 'm.room.member') {
    const stateKey = event?.getStateKey?.() || event?.event?.state_key || sender;
    const memberName = senderName(room, stateKey);
    const membership = content.membership || '';
    const prevMembership = prev.membership || '';

    const nextDisplay = String(content.displayname || '').trim();
    const prevDisplay = String(prev.displayname || '').trim();

    const nextAvatar = String(content.avatar_url || '').trim();
    const prevAvatar = String(prev.avatar_url || '').trim();

    if (nextDisplay && prevDisplay && nextDisplay !== prevDisplay) {
      return `${prevDisplay} is now ${nextDisplay}.`;
    }

    if (nextDisplay && !prevDisplay && stateKey === sender) {
      return `${stateKey} set their profile name to ${nextDisplay}.`;
    }

    if (nextAvatar && nextAvatar !== prevAvatar) {
      return `${memberName} changed their profile picture.`;
    }

    if (membership === 'join' && prevMembership !== 'join') {
      return `${memberName} joined the chat.`;
    }

    if (membership === 'leave' && prevMembership === 'join') {
      return `${memberName} left the chat.`;
    }
  }

  return '';
}

function renderSystemEvent(event, room) {
  const text = stateEventText(event, room);

  if (!text) return null;

  return el('div', {
    class: 'yanta-chat-system-event',
    dataset: {
      eventId: eventId(event),
    },
  }, text);
}

/**
 * Render a Matrix TimelineWindow event list.
 *
 * @param {Array} events Matrix events from TimelineWindow.getEvents().
 * @param {object} context Render context.
 * @returns {DocumentFragment}
 */
export function renderTimelineEvents(events = [], context = {}) {
  ensureYantaAiAttributionCss();

  const fragment = document.createDocumentFragment();

  const eventMap = new Map();

  for (const event of events) {
    const id = eventId(event);

    if (id) {
      eventMap.set(id, event);
    }
  }

  let previousRenderable = null;
  let previousDayTs = 0;

  for (const event of events) {
    const ts = eventTs(event);

    const shouldRender =
      (isMessageLike(event) && !isEditEvent(event)) ||
      isRenderableStateEvent(event);

    if (!shouldRender) continue;

    if (!previousDayTs || !sameDay(previousDayTs, ts)) {
      fragment.append(el('div', {
        class: 'yanta-chat-day-separator',
      }, dayLabel(ts)));

      previousDayTs = ts;
      previousRenderable = null;
    }

    if (isRenderableStateEvent(event)) {
      const node = renderSystemEvent(event, context.room);

      if (node) {
        fragment.append(node);
      }

      continue;
    }

    const sameSender =
      previousRenderable &&
      previousRenderable.getSender?.() === event.getSender?.();

    const closeInTime =
      previousRenderable &&
      Math.abs(eventTs(event) - eventTs(previousRenderable)) < FIVE_MINUTES;

    const grouped = !!(sameSender && closeInTime);

    const node = renderSingleMessage(event, {
      ...context,
      grouped,
      eventMap,
    });

    if (node) {
      fragment.append(node);
      previousRenderable = event;
    }
  }

  return fragment;
}

/**
 * Return the last message event suitable for read receipts.
 */
export function lastReadableEvent(events = []) {
  for (let i = events.length - 1; i >= 0; i--) {
    const event = events[i];

    if (isMessageLike(event) && !isEditEvent(event) && !isRedacted(event)) {
      return event;
    }
  }

  return null;
}

/**
 * Format a Matrix timestamp for compact room-list display.
 */
export function compactTime(ts) {
  if (!ts) return '';

  const now = Date.now();

  if (sameDay(ts, now)) {
    return timeLabel(ts);
  }

  return fmtDate(ts);
}