const FIVE_MINUTES = 5 * 60 * 1000;

const SAFE_FORMATTED_BODY_TAGS = [
  'b',
  'i',
  'em',
  'strong',
  'code',
  'pre',
  'a',
  'br',
  'del',
  'blockquote',
];

const SAFE_FORMATTED_BODY_ATTRS = {
  a: ['href', 'title', 'target', 'rel'],
};

const YANTA_AI_EVENT_KEY = 'com.yanta.ai';
const YANTA_AI_FOOTER_RE = /\n{1,3}— sent by YANTA AI\s*$/i;

function stripYantaAiFooter(text = '') {
  return String(text || '')
    .replace(YANTA_AI_FOOTER_RE, '')
    .trim();
}

function stripYantaAiFormattedFooter(html = '') {
  return String(html || '')
    .replace(
      /(?:<br\s*\/?>\s*){1,4}<em>\s*sent by YANTA AI\s*<\/em>\s*$/i,
      ''
    )
    .replace(
      /(?:<br\s*\/?>\s*){1,4}<span[^>]*>\s*sent by YANTA AI\s*<\/span>\s*$/i,
      ''
    )
    .trim();
}

function contentIsYantaAiGenerated(content = {}, {
  allowFooterFallback = true,
} = {}) {
  const body = String(content.body || '');

  return (
    content?.[YANTA_AI_EVENT_KEY]?.generated === true ||
    content?.[YANTA_AI_EVENT_KEY]?.sender === 'YANTA AI' ||
    (allowFooterFallback && YANTA_AI_FOOTER_RE.test(body))
  );
}

function displayContent(content = {}) {
  if (!contentIsYantaAiGenerated(content)) return content;

  const next = {
    ...content,
    body: stripYantaAiFooter(content.body || ''),
  };

  if (next.formatted_body) {
    next.formatted_body = stripYantaAiFormattedFooter(next.formatted_body);
  }

  return next;
}

function renderYantaAiBanner() {
  const node = el('div', {
    class: 'yanta-chat-ai-banner',
    title: 'This message was generated by YANTA AI and sent after user confirmation.',
  });

  node.innerHTML = `
    ${lucide('sparkles', 12)}
    <span>sent by YANTA AI</span>
  `;

  return node;
}

